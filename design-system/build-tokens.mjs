// Usage: node build-tokens.mjs   -> writes tokens.css, prints contrast table, exits 1 on any failure.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const root = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));

// ---- flatten: [{path:[...], value, type}] ; "$" keys are metadata
function leaves(node, path = [], type) {
  const out = [];
  const t = node.$type ?? type;
  if ('$value' in node) return [{ path, value: node.$value, type: t }];
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || typeof v !== 'object') continue;
    out.push(...leaves(v, [...path, k], t));
  }
  return out;
}

const byPath = new Map(); // full dotted path -> leaf (for alias resolution)
const blocks = {};       // block name -> [{name,value,path}]
const layerOf = (full) =>
  full[0] === 'semantic' ? [`semantic.${full[1]}`, full.slice(2)] : [full[0], full.slice(1)];

for (const l of leaves(root)) {
  byPath.set(l.path.join('.'), l);
  const [layer, rest] = layerOf(l.path);
  (blocks[layer] ??= []).push({ ...l, name: rest.join('-') });
}

const varName = (dotted) => layerOf(dotted.split('.'))[1].join('-');

function cssValue(l) {
  const v = l.value;
  if (Array.isArray(v)) return `cubic-bezier(${v.join(', ')})`;
  if (typeof v === 'string') {
    const m = v.match(/^\{(.+)\}$/);
    if (m) {
      if (!byPath.has(m[1])) throw new Error(`Unresolved alias ${v} in ${l.path.join('.')}`);
      return `var(--${varName(m[1])})`;
    }
  }
  return String(v);
}

function resolve(l) {
  const m = typeof l.value === 'string' && l.value.match(/^\{(.+)\}$/);
  return m ? resolve(byPath.get(m[1])) : l.value;
}

// ---- duplicate-name guard (light/dark and shared/compact/touch overlap by design)
const seen = new Map();
for (const layer of ['primitive', 'semantic.shared', 'semantic.light', 'component']) {
  for (const b of blocks[layer]) {
    if (seen.has(b.name)) throw new Error(`CSS name collision --${b.name}: ${seen.get(b.name)} vs ${b.path.join('.')}`);
    seen.set(b.name, b.path.join('.'));
  }
}
const names = (layer) => new Set(blocks[layer].map((b) => b.name));
const light = names('semantic.light');
const dark = names('semantic.dark');
for (const n of light) if (!dark.has(n)) throw new Error(`dark theme missing --${n}`);
for (const n of dark) if (!light.has(n)) throw new Error(`dark theme has extra --${n}`);
for (const layer of ['semantic.compact', 'semantic.touch'])
  for (const n of names(layer)) if (!seen.has(n)) throw new Error(`${layer} overrides unknown --${n}`);

// ---- emit CSS
const decl = (arr, ind) => arr.map((b) => `${ind}--${b.name}: ${cssValue(b)};`).join('\n');
const css = `/* GENERATED by build-tokens.mjs from tokens.json. Do not edit by hand. */
:root {
${['primitive', 'semantic.shared', 'semantic.light', 'component'].map((l) => `  /* ${l} */\n${decl(blocks[l], '  ')}`).join('\n\n')}
}

/* Dark theme: <html data-theme="dark"> */
[data-theme="dark"] {
  color-scheme: dark;
${decl(blocks['semantic.dark'], '  ')}
}

/* Compact density: <html data-density="compact"> */
[data-density="compact"] {
${decl(blocks['semantic.compact'], '  ')}
}

/* Coarse pointers always get >=44px targets, even in compact density */
@media (pointer: coarse) {
  :root, [data-density="compact"] {
${decl(blocks['semantic.touch'], '    ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root { --motion-duration: 0.01ms; --duration-fast: 0.01ms; --duration-base: 0.01ms; --duration-slow: 0.01ms; --duration-pulse: 0.01ms; }
}
`;
writeFileSync(join(dir, 'tokens.css'), css);

// ---- contrast check (WCAG 2.x)
const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const T = 4.5, UI = 3.0;
const pairs = [
  ['text.primary', 'surface.card', T], ['text.primary', 'surface.canvas', T], ['text.primary', 'surface.sunken', T], ['text.primary', 'surface.selected', T],
  ['text.secondary', 'surface.card', T], ['text.secondary', 'surface.canvas', T], ['text.secondary', 'surface.sunken', T],
  ['text.muted', 'surface.card', T], ['text.muted', 'surface.canvas', T], ['text.muted', 'surface.sunken', T],
  ['text.brand', 'surface.card', T], ['text.brand', 'surface.canvas', T],
  ['text.inverse', 'surface.inverse', T],
  ['action.primary.text', 'action.primary.bg', T], ['action.primary.text', 'action.primary.bg-hover', T], ['action.primary.text', 'action.primary.bg-active', T],
  ['action.secondary.text', 'action.secondary.bg', T], ['action.secondary.text', 'action.secondary.bg-hover', T], ['action.secondary.text', 'action.secondary.bg-active', T],
  ['action.ghost.text', 'surface.card', T], ['action.ghost.text', 'action.ghost.bg-hover', T], ['action.ghost.text', 'action.ghost.bg-active', T],
  ['action.danger.text', 'action.danger.bg', T], ['action.danger.text', 'action.danger.bg-hover', T], ['action.danger.text', 'action.danger.bg-active', T],
  ['nav.active-text', 'nav.active-bg', T], ['nav.item-text', 'surface.card', T], ['nav.item-text', 'nav.item-hover', T],
  ['tooltip.text', 'tooltip.bg', T],
  ...['success', 'danger', 'warning', 'info', 'neutral'].map((s) => [`status.${s}.text`, `status.${s}.bg`, T]),
  // non-text UI: control boundaries and focus must be visible on BOTH canvas and card
  ['border.control', 'surface.card', UI], ['border.control', 'surface.canvas', UI],
  ['border.error', 'surface.card', UI],
  ['focus.ring', 'surface.card', UI], ['focus.ring', 'surface.canvas', UI],
  ['action.secondary.border', 'surface.card', UI],
  ['chart.series-1', 'surface.card', UI], ['chart.series-2', 'surface.card', UI], ['chart.series-3', 'surface.card', UI],
  ['chart.series-4', 'surface.card', UI], ['chart.series-5', 'surface.card', UI], ['chart.bar-highlight', 'surface.card', UI],
];

let fails = 0;
for (const theme of ['light', 'dark']) {
  console.log(`\n[${theme}]`);
  for (const [fg, bg, min] of pairs) {
    const get = (n) => resolve(byPath.get(`semantic.${theme}.color.${n}`) ?? (() => { throw new Error(`no token ${n}`); })());
    const r = ratio(get(fg), get(bg));
    const ok = r >= min;
    if (!ok) fails++;
    console.log(`${ok ? 'PASS' : 'FAIL'}  ${r.toFixed(2).padStart(5)}:1  (min ${min})  ${fg} on ${bg}`);
  }
}
console.log(`\ntokens.css written. ${fails ? fails + ' contrast failure(s).' : 'All contrast checks pass.'}`);
process.exit(fails ? 1 : 0);
